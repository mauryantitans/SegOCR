#!/usr/bin/env python3
"""Regenerate docs/STATUS.md: which lessons, assessments and projects are authored and validated.

    python scripts/status_report.py
"""
from __future__ import annotations

import datetime as dt
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.config import get_settings  # noqa: E402
from app.content.repository import Repository  # noqa: E402


def main():
    root = get_settings().content_dir
    repo = Repository.load(root)
    cap_dir = root / "generated" / "captures"
    lines = ["# Content Status", "",
             f"_Generated by `backend/scripts/status_report.py` on {dt.date.today().isoformat()}. Do not edit by hand._", "",
             "Legend: ✅ authored and validated (captured on real MySQL) · 📝 authored, capture missing · ⏳ planned (outline only)", ""]
    total = authored = validated = 0
    rows = []
    for m in repo.modules:
        ls = [repo.lessons[l["id"]] for c in m["chapters"] for l in c["lessons"]]
        a = [l for l in ls if l.doc]
        v = [l for l in a if (cap_dir / f"{l.id}.json").exists()]
        total += len(ls); authored += len(a); validated += len(v)
        has_assessment = f"{m['id']}-assessment" in repo.assessments
        rows.append(f"| {m['number']} | {m['title']} | {len(v)}/{len(ls)} | {'✅' if has_assessment else '⏳'} |")
    lines += [f"**Lessons:** {validated} validated, {authored} authored, {total} in the curriculum. "
              f"**Exercises:** {len(repo.exercises)} · **Quiz/assessment questions:** {len(repo.questions)}", "",
              "| # | Module | Lessons validated | Assessment |", "|---|---|---|---|", *rows, ""]
    for m in repo.modules:
        lines += [f"## Module {m['number']}: {m['title']}", ""]
        for c in m["chapters"]:
            for l in c["lessons"]:
                rec = repo.lessons[l["id"]]
                mark = "⏳" if not rec.doc else ("✅" if (cap_dir / f"{rec.id}.json").exists() else "📝")
                lines.append(f"- {mark} `{rec.id}` — {rec.title} ({rec.level})")
        lines.append("")
    lines += ["## Projects", ""]
    for p in repo.projects.values():
        mark = "⏳" if not p["authored"] else ("✅" if (cap_dir / f"{p['id']}.json").exists() else "📝")
        lines.append(f"- {mark} `{p['id']}` — {p['title']} ({p['level']})")
    out = root.parent / "docs" / "STATUS.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}: {validated}/{total} lessons validated")


if __name__ == "__main__":
    main()
